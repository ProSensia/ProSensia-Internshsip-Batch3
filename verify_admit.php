<?php
// verify_admit.php — Public Admit Card Verification Page
error_reporting(E_ALL);
ini_set('display_errors', 0);  // hide errors in production

require_once __DIR__ . '/includes/connection.php'; // creates $pdo

$uid = isset($_GET['uid']) ? (int)$_GET['uid'] : 0;
if ($uid <= 0) {
    http_response_code(400);
    die('Invalid request.');
}

// Fetch user + profile + form_c + enrollment
try {
    $stmt = $pdo->prepare('
        SELECT u.name, u.email, u.status,
               p.father_name, p.cnic, p.reg_number, p.department, p.semester, p.phone, p.address,
               f.employer_name, f.employer_dept, f.joining_date, f.start_date, f.end_date, f.status AS form_status,
               e.track, e.batch
        FROM users u
        LEFT JOIN profiles p ON p.user_id = u.id
        LEFT JOIN form_c f ON f.user_id = u.id
        LEFT JOIN enrollments e ON e.user_id = u.id
        WHERE u.id = ?
    ');
    $stmt->execute([$uid]);
    $data = $stmt->fetch(PDO::FETCH_ASSOC);
} catch (PDOException $e) {
    http_response_code(500);
    die('Database error.');
}

if (!$data) {
    http_response_code(404);
    die('No record found.');
}

// Only show if form_c is submitted/approved (admit card is valid)
$formStatus = strtolower(trim($data['form_status'] ?? ''));
if (!in_array($formStatus, ['submitted', 'approved'])) {
    http_response_code(404);
    die('Admit card not available for this candidate.');
}

// Prepare data for display
$name         = $data['name'] ?? '';
$email        = $data['email'] ?? '';
$father       = $data['father_name'] ?? '';
$cnic         = $data['cnic'] ?? '';
$regNo        = $data['reg_number'] ?? '';
$department   = $data['department'] ?? 'Electrical and Computer Engineering';
$semester     = $data['semester'] ?? '';
$phone        = $data['phone'] ?? '';
$address      = $data['address'] ?? '';
$employer     = $data['employer_name'] ?? '';
$employerDept = $data['employer_dept'] ?? '';
$joining      = $data['joining_date'] ?? '';
$startDate    = $data['start_date'] ?? '';
$endDate      = $data['end_date'] ?? '';
$track        = $data['track'] ?? '';
$batch        = $data['batch'] ?? '';

// Download URL for the admit card PDF
$pdfUrl = 'intern/admit_card.php';  // relative to root, or adjust if needed
?>
