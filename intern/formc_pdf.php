<?php
// Form C — Internship Placement Proforma — exact match to official document
require_once __DIR__ . '/../includes/auth.php';
require_login();
require_once __DIR__ . '/../lib/fpdf.php';

$me = current_user();
$role = $me['role'];

// Determine which user's form to show
$target = (in_array($role, ['super_admin', 'management']) && !empty($_GET['uid'])) ? (int)$_GET['uid'] : $me['id'];

// Fetch user, profile, and form_c data
$u = $pdo->prepare('SELECT u.*, p.* FROM users u LEFT JOIN profiles p ON p.user_id = u.id WHERE u.id = ?');
$u->execute([$target]);
$student = $u->fetch();
if (!$student) {
    http_response_code(404);
    exit('Student not found');
}

$fc = $pdo->prepare('SELECT * FROM form_c WHERE user_id = ?');
$fc->execute([$target]);
$f = $fc->fetch();

// Intern can only download if form is approved; admin can always download
if ($role === 'intern' && (!$f || $f['status'] !== 'approved')) {
    http_response_code(403);
    exit('Form C not approved yet. You can download only after super admin approval.');
}

// Logo paths
$logo_rel     = setting('logo_path', 'assets/img/prosensia-logo.png');
$partner_rel  = setting('partner_logo_path', '');
$logo         = __DIR__ . '/../' . $logo_rel;
$partner      = $partner_rel ? __DIR__ . '/../' . $partner_rel : null;

// Paths to stamp PNG images (place your own files in assets/img/)
$employerStamp = __DIR__ . '/../assets/img/employer-stamp.png';
$hodStamp      = __DIR__ . '/../assets/img/hod-stamp.png';

class ProformaPDF extends FPDF
{
    public $logo;
    public $partner;
    public $employerStamp;
    public $hodStamp;

    function Header()
    {
        // Top left logo
        if ($this->logo && file_exists($this->logo)) {
            $this->Image($this->logo, 12, 8, 36);
        }
        // Top right partner logo
        if ($this->partner && file_exists($this->partner)) {
            $this->Image($this->partner, 162, 8, 36);
        }
        // University name and address
        $this->SetY(12);
        $this->SetFont('Helvetica', 'B', 12);
        $this->Cell(0, 6, 'Pak-Austria Fachhochschule: Institute of Applied Sciences and Technology, Mang, Haripur, KPK', 0, 1, 'C');
        $this->SetFont('Helvetica', '', 9);
        $this->Cell(0, 5, 'Website: https://www.paf-iast.edu.pk, Tel: +92-995-645112-116, Fax: +92-995-645117', 0, 1, 'C');
        $this->Ln(4);
        $this->SetFont('Helvetica', 'B', 14);
        $this->Cell(0, 8, 'Internship Placement Proforma', 0, 1, 'C');
        $this->Ln(6);
    }

    function Footer()
    {
        $this->SetY(-14);
        $this->SetFont('Helvetica', 'I', 8);
        $this->SetTextColor(120, 120, 120);
        $this->Cell(0, 5, 'Generated by ProSensia Portal - Page ' . $this->PageNo() . '/{nb}', 0, 0, 'C');
        $this->SetTextColor(0, 0, 0);
    }

    function labeledField($label, $value, $x, $y, $w = 80, $h = 10)
    {
        $this->SetXY($x, $y);
        $this->SetFont('Helvetica', 'B', 10);
        $this->Cell($w * 0.3, $h, $label, 0, 0);
        $this->SetFont('Helvetica', '', 10);
        $val = ($value !== '' && $value !== null) ? (string)$value : '_________________________';
        $this->Cell($w * 0.7, $h, $val, 0, 1);
    }
}

$pdf = new ProformaPDF('P', 'mm', 'A4');
$pdf->logo          = $logo;
$pdf->partner       = $partner;
$pdf->employerStamp = $employerStamp;
$pdf->hodStamp      = $hodStamp;
$pdf->AliasNbPages();
$pdf->SetMargins(15, 45, 15);
$pdf->SetAutoPageBreak(true, 18);
$pdf->AddPage();

// Student Information Section
$pdf->SetFont('Helvetica', 'B', 11);
$pdf->Cell(0, 8, 'Student Information:', 0, 1);
$pdf->SetFont('Helvetica', '', 10);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(40, 8, 'Student Name:', 0, 0);
$pdf->Cell(80, 8, $student['name'] ?: '_________________________', 0, 0);
$pdf->SetX(135);
$pdf->Cell(40, 8, 'Father Name:', 0, 0);
$pdf->Cell(50, 8, $student['father_name'] ?: '_________________________', 0, 1);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(40, 8, 'Registration #:', 0, 0);
$pdf->Cell(80, 8, $student['reg_number'] ?: '_________________________', 0, 0);
$pdf->SetX(135);
$pdf->Cell(40, 8, 'Department:', 0, 0);
$pdf->Cell(50, 8, $student['department'] ?: 'Electrical and Computer Engineering', 0, 1);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(40, 8, 'CNIC #:', 0, 0);
$pdf->Cell(80, 8, $student['cnic'] ?: '_________________________', 0, 0);
$pdf->SetX(135);
$pdf->Cell(40, 8, 'Contact number:', 0, 0);
$pdf->Cell(50, 8, $student['phone'] ?: '_________________________', 0, 1);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(40, 8, 'Email:', 0, 0);
$pdf->Cell(80, 8, $student['email'] ?: '_________________________', 0, 0);
$pdf->SetX(135);
$pdf->Cell(40, 8, 'Internship semester:', 0, 0);
$pdf->Cell(50, 8, $student['semester'] ?: '_________________________', 0, 1);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(40, 8, 'Present Address:', 0, 0);
$pdf->MultiCell(160, 8, $student['address'] ?: '_________________________', 0, 'L');

$pdf->Ln(4);

// Employer Section
$pdf->SetFont('Helvetica', 'B', 11);
$pdf->Cell(0, 8, 'To be filled by Internship Industry/Organization Representative', 0, 1);
$pdf->SetFont('Helvetica', '', 10);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(50, 8, 'Internship employer name:', 0, 0);
$pdf->Cell(130, 8, $f['employer_name'] ?: '_________________________', 0, 1);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(50, 8, 'Internship department:', 0, 0);
$pdf->Cell(130, 8, $f['employer_dept'] ?: '_________________________', 0, 1);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(50, 8, 'Joining date:', 0, 0);
$pdf->Cell(130, 8, $f['joining_date'] ?: '_________________________', 0, 1);

$y = $pdf->GetY();
$pdf->SetXY(15, $y);
$pdf->Cell(50, 8, 'Dates of internship:', 0, 0);
$dates = ($f['start_date'] ?? '') . '   to   ' . ($f['end_date'] ?? '');
$pdf->Cell(130, 8, $dates ?: '_________________________', 0, 1);

$pdf->Ln(6);
$pdf->SetFont('Helvetica', 'I', 10);
$pdf->MultiCell(0, 6, 'I hereby declare that the above-mentioned information is correct to the best of my knowledge.');
$pdf->Ln(10);

// Signature & Stamp blocks with automatic PNG images
$y = $pdf->GetY();
$pdf->SetFont('Helvetica', '', 10);
$pdf->Line(20, $y, 90, $y);
$pdf->Line(120, $y, 190, $y);
$pdf->SetXY(20, $y + 2);
$pdf->Cell(70, 6, 'Approval of Employer', 0, 0, 'C');
$pdf->SetXY(120, $y + 2);
$pdf->Cell(70, 6, 'Approval by HoD / Chairman', 0, 1, 'C');
$pdf->SetXY(20, $y + 8);
$pdf->SetFont('Helvetica', 'I', 8);
$pdf->Cell(70, 4, '(Signature and Stamp)', 0, 0, 'C');
$pdf->SetXY(120, $y + 8);
$pdf->Cell(70, 4, '(Signature and Stamp)', 0, 1, 'C');

// Place stamp images if they exist
if (file_exists($pdf->employerStamp)) {
    $pdf->Image($pdf->employerStamp, 50, $y - 8, 30);
}
if (file_exists($pdf->hodStamp)) {
    $pdf->Image($pdf->hodStamp, 145, $y - 8, 30);
}

// Output PDF
$filename = 'FormC_' . preg_replace('/[^A-Za-z0-9_-]/', '_', $student['name']) . '.pdf';
$pdf->Output('I', $filename);