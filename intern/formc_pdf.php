<?php
// formc_pdf.php — compact one-page version, no logo background
require_once __DIR__ . '/../includes/auth.php';
require_login();
require_once __DIR__ . '/../lib/fpdf.php';

$me = current_user();
$role = $me['role'];
$target = (in_array($role, ['super_admin', 'management']) && !empty($_GET['uid'])) ? (int)$_GET['uid'] : $me['id'];

$u = $pdo->prepare('SELECT u.*, p.* FROM users u LEFT JOIN profiles p ON p.user_id = u.id WHERE u.id = ?');
$u->execute([$target]);
$student = $u->fetch();
if (!$student) exit('Student not found');

$fc = $pdo->prepare('SELECT * FROM form_c WHERE user_id = ?');
$fc->execute([$target]);
$f = $fc->fetch();
if ($role === 'intern' && (!$f || $f['status'] !== 'approved')) exit('Not approved');

$refNumber = 'ProSensiaB' . str_pad(3000 + (int)($f['id'] ?? 0), 4, '0', STR_PAD_LEFT);
$protocol = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
$host = $_SERVER['HTTP_HOST'];
$verifyUrl = $protocol . '://' . $host . '/verify_formc.php?ref=' . urlencode($refNumber);

// QR code
$tempDir = __DIR__ . '/../temp';
if (!is_dir($tempDir)) mkdir($tempDir, 0777, true);
$qrTempFile = $tempDir . '/qr_' . uniqid() . '.png';
$qrData = @file_get_contents('https://quickchart.io/qr?text=' . urlencode($verifyUrl) . '&size=150&margin=1');
if ($qrData && file_put_contents($qrTempFile, $qrData)) $qrOk = true;
else $qrOk = false;

// ProSensia logo
$proSensiaLogo = null;
$stmt = $pdo->prepare("SELECT v FROM settings WHERE k = 'logo_path'");
$stmt->execute();
$logoPath = $stmt->fetchColumn();
if ($logoPath) {
    $full = __DIR__ . '/../' . ltrim($logoPath, '/');
    if (file_exists($full)) {
        $ext = strtolower(pathinfo($full, PATHINFO_EXTENSION));
        if ($ext === 'webp' && function_exists('imagecreatefromwebp')) {
            $tempPng = $tempDir . '/logo_ps_' . uniqid() . '.png';
            $img = imagecreatefromwebp($full);
            if ($img) { imagepng($img, $tempPng); imagedestroy($img); $proSensiaLogo = $tempPng; register_shutdown_function(function() use ($tempPng) { @unlink($tempPng); }); }
        } elseif (in_array($ext, ['jpg','jpeg','png','gif'])) $proSensiaLogo = $full;
    }
}

// Partner logo (small)
$partnerLogo = null;
$stmt = $pdo->prepare("SELECT v FROM settings WHERE k = 'partner_logo_path'");
$stmt->execute();
$partnerPath = $stmt->fetchColumn();
if ($partnerPath) {
    $full = __DIR__ . '/../' . ltrim($partnerPath, '/');
    if (file_exists($full)) {
        $ext = strtolower(pathinfo($full, PATHINFO_EXTENSION));
        if ($ext === 'webp' && function_exists('imagecreatefromwebp')) {
            $tempPng = $tempDir . '/logo_partner_' . uniqid() . '.png';
            $img = imagecreatefromwebp($full);
            if ($img) { imagepng($img, $tempPng); imagedestroy($img); $partnerLogo = $tempPng; register_shutdown_function(function() use ($tempPng) { @unlink($tempPng); }); }
        } elseif (in_array($ext, ['jpg','jpeg','png','gif'])) $partnerLogo = $full;
    }
}

class OnePageFormC extends FPDF {
    function Header() {}
    function Footer() { $this->SetY(-10); $this->SetFont('Helvetica','I',7); $this->Cell(0,4,'Generated by ProSensia Portal - Page '.$this->PageNo().'/{nb}',0,0,'C'); }
}

$pdf = new OnePageFormC('P','mm','A4');
$pdf->AliasNbPages();
$pdf->SetMargins(12,12,12);
$pdf->AddPage();
$pdf->SetAutoPageBreak(false); // we control page break manually
$pdf->SetFont('Helvetica','',9);

// === TOP ROW: ProSensia logo (left, no bg) + Reference (right) ===
$logoX = 12; $logoY = 8; $logoW = 25; $logoH = 15;
if ($proSensiaLogo) $pdf->Image($proSensiaLogo, $logoX, $logoY, $logoW);
$pdf->SetY(12); $pdf->SetX(160); $pdf->SetFont('Helvetica','B',9); $pdf->Cell(35,5,'Ref: '.$refNumber,0,1,'R');

// === SECOND ROW: Partner logo (tiny) + University header ===
$partnerY = 28;
$partnerW = 18; // small width
if ($partnerLogo) $pdf->Image($partnerLogo, 12, $partnerY, $partnerW);
$textX = $partnerLogo ? 12+$partnerW+5 : 12;

$pdf->SetY($partnerY); $pdf->SetX($textX); $pdf->SetFont('Helvetica','B',9);
$pdf->MultiCell(130,4,"Pak-Austria Fachhochschule: Institute of Applied Sciences and Technology, Mang, Haripur, KPK",0,'L');
$pdf->SetX($textX); $pdf->SetFont('Helvetica','',8);
$pdf->MultiCell(130,3.5,"Website: https://www.paf-iast.edu.pk, Tel: +92-995-645112-116, Fax: +92-995-645117",0,'L');

// === Main title ===
$pdf->SetY(48); $pdf->SetFont('Helvetica','B',12); $pdf->Cell(0,6,'Internship Placement Proforma',0,1,'C'); $pdf->Ln(3);

// === Student Information (compact two-column) ===
$pdf->SetFont('Helvetica','B',9); $pdf->Cell(0,5,'Student Information:',0,1); $pdf->SetFont('Helvetica','',9);
$left=12; $right=105; $h=5;
$y = $pdf->GetY();

$pdf->SetXY($left,$y); $pdf->Cell(32,$h,'Student Name:',0,0); $pdf->Cell(55,$h,$student['name']?:'________',0,0);
$pdf->SetXY($right,$y); $pdf->Cell(30,$h,'Father Name:',0,0); $pdf->Cell(55,$h,$student['father_name']?:'________',0,1);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(32,$h,'Registration #:',0,0); $pdf->Cell(55,$h,$student['reg_number']?:'________',0,0);
$pdf->SetXY($right,$y); $pdf->Cell(30,$h,'Department:',0,0); $pdf->Cell(55,$h,$student['department']?:'Electrical and Computer Engineering',0,1);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(32,$h,'CNIC #:',0,0); $pdf->Cell(55,$h,$student['cnic']?:'________',0,0);
$pdf->SetXY($right,$y); $pdf->Cell(30,$h,'Contact number:',0,0); $pdf->Cell(55,$h,$student['phone']?:'________',0,1);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(32,$h,'Email:',0,0); $pdf->Cell(55,$h,$student['email']?:'________',0,0);
$pdf->SetXY($right,$y); $pdf->Cell(30,$h,'Internship semester:',0,0); $pdf->Cell(55,$h,$student['semester']?:'________',0,1);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(32,$h,'Present Address:',0,0);
$pdf->MultiCell(160,$h,$student['address']?:'________',0,'L');
$pdf->Ln(2);

// === Employer Section ===
$pdf->SetFont('Helvetica','B',9); $pdf->Cell(0,5,'To be filled by Internship Industry/Organization Representative',0,1);
$pdf->SetFont('Helvetica','',9);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(45,$h,'Internship employer name:',0,0); $pdf->Cell(130,$h,$f['employer_name']?:'________',0,1);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(45,$h,'Internship department:',0,0); $pdf->Cell(130,$h,$f['employer_dept']?:'________',0,1);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(45,$h,'Joining date:',0,0); $pdf->Cell(130,$h,$f['joining_date']?:'________',0,1);
$y=$pdf->GetY();
$pdf->SetXY($left,$y); $pdf->Cell(45,$h,'Dates of internship:',0,0);
$dates = ($f['start_date']??'').'   to   '.($f['end_date']??'');
$pdf->Cell(130,$h,$dates?:'________',0,1);
$pdf->Ln(3);

// Declaration & digital signature notice (compact)
$pdf->SetFont('Helvetica','I',8);
$pdf->MultiCell(0,4,'I hereby declare that the above-mentioned information is correct to the best of my knowledge.');
$pdf->Ln(2);
$pdf->SetFont('Helvetica','',8);
$pdf->MultiCell(0,4,'This document is digitally signed and requires no physical stamp as it is generated directly from the ProSensia portal.');
$pdf->Ln(1);
$pdf->SetFont('Helvetica','B',8);
$pdf->Cell(0,4,'Digitally Signed by ProSensia',0,1,'L');
$pdf->SetFont('Helvetica','',7);
$pdf->Cell(0,3,'Date: '.date('Y-m-d H:i:s'),0,1,'L');
$pdf->Ln(3);

// QR code (smaller) and signature lines side by side
$qrSize = 25;
if ($qrOk && file_exists($qrTempFile)) {
    $pdf->Image($qrTempFile, 170, $pdf->GetY(), $qrSize);
    register_shutdown_function(function() use ($qrTempFile) { @unlink($qrTempFile); });
}

// Signature lines (left side, below content)
$sigY = $pdf->GetY() + 5;
$pdf->Line(15, $sigY, 85, $sigY);
$pdf->Line(100, $sigY, 170, $sigY);
$pdf->SetXY(15, $sigY+2); $pdf->Cell(70,4,'Approval of Employer',0,0,'C');
$pdf->SetXY(100, $sigY+2); $pdf->Cell(70,4,'Approval by HoD / Chairman',0,1,'C');
$pdf->SetXY(15, $sigY+6); $pdf->SetFont('Helvetica','I',7); $pdf->Cell(70,3,'(Digital signature on file)',0,0,'C');
$pdf->SetXY(100, $sigY+6); $pdf->Cell(70,3,'(Digital signature on file)',0,1,'C');

$pdf->Output('I', 'FormC_'.preg_replace('/[^A-Za-z0-9_-]/','_',$student['name']).'.pdf');
?>